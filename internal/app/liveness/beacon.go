// Package liveness связывает признак жизни процесса с признаком жизни торговли.
//
// До сих пор это были разные вещи, различавшиеся только на словах: файл биения
// писала горутина со своим таймером, ничего не знавшая об акторах. Живой
// процесс с мёртвым актором выглядел здоровым — и для сторожа, и для
// healthcheck контейнера. 13 августа так и вышло: очередь актора переполнилась,
// торговля встала, а Docker тридцать пять минут показывал healthy
// (PLAN.md §0, дефект 3).
//
// Маяк переворачивает зависимость. Признак жизни теперь производится актором и
// только им; всё остальное его читает.
package liveness

import (
	"sync"
	"time"

	"github.com/nd/mm-standx/internal/domain/market"
	"github.com/nd/mm-standx/internal/ports"
)

// Beacon хранит момент последнего такта по каждому ожидаемому инструменту.
//
// Мьютекс здесь уместен вопреки правилу «в app мьютексов нет»: правило
// защищает состояние актора, которым владеет одна горутина, а это — общая
// таблица наблюдения, куда пишут все акторы и читают сторож с HTTP-обработчиком.
// Захват держится на время одного присваивания и в горячий путь не попадает
// иначе как этим присваиванием.
type Beacon struct {
	// threshold — молчание, после которого актор считается мёртвым.
	//
	// Порог, а не «последний такт старше периода»: такт актора 250 мс, и
	// требовать его точности значило бы объявлять смерть на каждой паузе сборки
	// мусора. Порог берётся заметно крупнее такта и заметно меньше срока,
	// по которому судит сторож, — иначе первым сработает он и снимет котировки
	// прежде, чем процесс успеет сказать о себе хоть что-то.
	threshold time.Duration

	mu   sync.RWMutex
	last map[market.Symbol]time.Time
}

// New заводит маяк на перечисленные инструменты.
//
// Отсчёт для каждого начинается с now, а не с нуля: инструмент, не тикнувший
// ещё ни разу, обязан считаться молчащим по тому же правилу, что и умерший.
// Иначе процесс, у которого актор не поднялся вовсе, получал бы бессрочную
// фору — ровно тот случай, который сторож и должен ловить (PLAN.md §13:
// «Сторож следил только за инструментами, от которых данные уже приходили»).
func New(symbols []market.Symbol, threshold time.Duration, now time.Time) *Beacon {
	last := make(map[market.Symbol]time.Time, len(symbols))
	for _, s := range symbols {
		last[s] = now
	}
	return &Beacon{threshold: threshold, last: last}
}

// Beat отмечает такт актора.
//
// Незарегистрированный инструмент игнорируется: список ожидаемых задаётся при
// сборке, и принимать отметки от кого угодно значило бы разрешить актору,
// которого никто не ждёт, поддерживать процесс живым.
func (b *Beacon) Beat(s market.Symbol, at time.Time) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if _, expected := b.last[s]; !expected {
		return
	}
	// Только вперёд: запоздавший такт не имеет права омолодить отметку.
	if at.After(b.last[s]) {
		b.last[s] = at
	}
}

// Stalest возвращает инструмент, молчащий дольше всех, если такой есть.
func (b *Beacon) Stalest(now time.Time) (market.Symbol, time.Duration, bool) {
	b.mu.RLock()
	defer b.mu.RUnlock()

	var (
		worst  market.Symbol
		silent time.Duration
	)
	for s, at := range b.last {
		if d := now.Sub(at); d > silent {
			worst, silent = s, d
		}
	}
	if silent <= b.threshold {
		return "", 0, false
	}
	return worst, silent, true
}

var (
	_ ports.Liveness       = (*Beacon)(nil)
	_ ports.LivenessSource = (*Beacon)(nil)
)
