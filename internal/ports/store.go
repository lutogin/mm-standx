package ports

// StateStore сохраняет небольшие снимки состояния между запусками процесса.
//
// Существует ради одного класса данных: счётчиков защитного контура. Лимит
// дневного убытка, который обнуляется при перезапуске, не защищает ни от чего —
// цикл «сработала защита, процесс подняли заново» исчерпывает депозит по частям
// и выглядит при этом как штатная работа.
//
// Хранилище намеренно примитивно. Журнал ордеров и почасовая статистика — это
// растущие во времени ряды, им нужна встраиваемая база; здесь же речь о паре
// сотен байт, которые обязаны пережить kill -9 и читаться человеком в момент
// разбора инцидента без специальных средств.
type StateStore interface {
	// Load читает снимок в into. Отсутствие снимка не ошибка: первый запуск —
	// штатный сценарий, и отличать его от сбоя чтения обязан вызывающий.
	Load(name string, into any) (found bool, err error)

	// Save записывает снимок атомарно: наблюдатель видит либо прежнее
	// содержимое, либо новое целиком, но никогда половину.
	Save(name string, value any) error
}
