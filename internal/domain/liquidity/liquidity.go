// Package liquidity судит, достаточно ли в стакане глубины, чтобы котировать
// сторону.
//
// ЧИСЛО ИЗМЕРЯЛОСЬ И ВЫБРАСЫВАЛОСЬ. Актор считает нотионал в пределах полосы
// награды по каждой стороне каждый такт и печатает его в сводке
// (depth_bid_usd, depth_ask_usd). В решениях он не участвовал нигде: то, что
// в policy зовётся глубиной, — это дистанция минус половина спреда, к
// ликвидности отношения не имеющая, а посчитанный из неё Quote.Margin
// встречался только в строке лога.
//
// Замер боевого счёта 1 сентября 2026, 23 залива за сутки: 70% из них пришли
// при глубине своей стороны в нижней четверти суточного распределения, а два
// самых крупных (по 10 XAU) — на первом и третьем перцентиле. Ордер ставился
// туда, где перед ним не стояло почти ничего, и сам становился лучшей ценой.
//
// Порог задан долей от собственной недавней нормы, а не суммой в долларах.
// Абсолютное число протухает при первой же смене баланса, инструмента или
// часа суток; отношение к своей же медиане переживает всё это.
package liquidity

import (
	"slices"
	"time"

	"github.com/nd/mm-standx/internal/domain/market"
)

// Config — настройки оценки.
type Config struct {
	// Window — горизонт, по которому считается норма.
	Window time.Duration
	// SampleEvery — минимальный промежуток между замерами.
	//
	// БЕЗ НЕГО ОКНО МЕРЯЕТ НЕ ВРЕМЯ, А СОБЫТИЯ. Observe вызывается из такта
	// актора, а такт идёт по приходу рыночных данных: замер 1 сентября 2026
	// даёт 3.4 обновления стакана в секунду плюс mark и события ордеров.
	// Без прореживания в тридцатиминутном окне копится порядка семи тысяч
	// замеров, и следствий три, каждое портит своё:
	//
	//   - MinSamples в 40 набирается за десять секунд, а не за минуты, то есть
	//     настройка зрелости перестаёт означать написанное;
	//   - медиана считается по семи тысячам значений на каждом такте;
	//   - и главное: частота событий сама зависит от рынка. Busy-периоды
	//     дают больше замеров и перевешивают медиану, то есть норма смещается
	//     ровно тогда, когда она нужнее всего.
	//
	// Ноль возвращает замер на каждом вызове.
	SampleEvery time.Duration
	// MinSamples — сколько замеров нужно, чтобы норме можно было верить.
	// До этого сторона считается пригодной: молчать из-за незрелой оценки
	// значит платить присутствием за отсутствие данных.
	//
	// Считается в замерах, а не в минутах, и вместе с SampleEvery задаёт
	// именно время: 300 при замере раз в секунду — это пять минут.
	MinSamples int
	// ThinFraction — доля медианы окна, ниже которой сторона объявляется
	// тонкой. Ноль отключает проверку целиком.
	ThinFraction float64
}

// Verdict — что известно о стороне прямо сейчас.
type Verdict struct {
	// Ready сообщает, набралось ли замеров для суждения.
	Ready bool
	// Thin — глубина упала ниже доли от нормы.
	Thin bool
	// DepthUSD — текущий нотионал в полосе награды.
	DepthUSD float64
	// MedianUSD — норма по окну.
	MedianUSD float64
	// ThresholdUSD — граница, ниже которой сторона тонка.
	ThresholdUSD float64
}

type sample struct {
	at    time.Time
	depth float64
}

// Estimator хранит окно наблюдений по каждой стороне.
//
// Владеет им актор и обращается к нему из своей единственной горутины,
// поэтому синхронизации здесь нет и быть не должно.
type Estimator struct {
	cfg  Config
	bids []sample
	asks []sample
	// scratch переиспользуется под сортировку: медиана считается на каждом
	// такте по обеим сторонам, и аллокация здесь была бы чистым мусором.
	scratch []float64
}

// New создаёт оценку по конфигурации.
func New(cfg Config) *Estimator { return &Estimator{cfg: cfg} }

func (e *Estimator) sideOf(s market.Side) *[]sample {
	if s == market.Buy {
		return &e.bids
	}
	return &e.asks
}

// Observe добавляет замер и забывает вышедшие из окна.
//
// Замеры чаще SampleEvery отбрасываются: окно обязано мерить время, а не
// частоту рыночных событий.
func (e *Estimator) Observe(side market.Side, depthUSD float64, at time.Time) {
	if e.cfg.Window <= 0 {
		return
	}
	q := e.sideOf(side)
	if n := len(*q); n > 0 && e.cfg.SampleEvery > 0 &&
		at.Sub((*q)[n-1].at) < e.cfg.SampleEvery {
		return
	}
	*q = append(*q, sample{at: at, depth: depthUSD})
	cutoff := at.Add(-e.cfg.Window)
	drop := 0
	for drop < len(*q) && !(*q)[drop].at.After(cutoff) {
		drop++
	}
	if drop > 0 {
		*q = append((*q)[:0], (*q)[drop:]...)
	}
}

// Verdict судит сторону по последнему замеру.
//
// Пустое окно и незрелая оценка дают Thin=false: проверка существует, чтобы
// убирать актора из опасного стакана, а не чтобы держать его вне рынка, пока
// нечего сказать.
func (e *Estimator) Verdict(side market.Side, _ time.Time) Verdict {
	q := *e.sideOf(side)
	if len(q) == 0 {
		return Verdict{}
	}
	v := Verdict{DepthUSD: q[len(q)-1].depth}
	if e.cfg.ThinFraction <= 0 || len(q) < e.cfg.MinSamples {
		return v
	}
	v.Ready = true
	v.MedianUSD = e.median(q)
	v.ThresholdUSD = v.MedianUSD * e.cfg.ThinFraction
	v.Thin = v.MedianUSD > 0 && v.DepthUSD < v.ThresholdUSD
	return v
}

// median — медиана глубины по окну.
//
// Медиана, а не среднее: глубина стакана распределена с тяжёлым правым
// хвостом — одна крупная заявка сдвигает среднее и вместе с ним порог,
// объявляя тонким совершенно обычный стакан.
func (e *Estimator) median(q []sample) float64 {
	e.scratch = e.scratch[:0]
	for _, s := range q {
		e.scratch = append(e.scratch, s.depth)
	}
	slices.Sort(e.scratch)
	return e.scratch[len(e.scratch)/2]
}
