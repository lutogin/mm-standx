// Package liquidity судит, достаточно ли в стакане глубины, чтобы котировать
// сторону.
//
// ЧИСЛО ИЗМЕРЯЛОСЬ И ВЫБРАСЫВАЛОСЬ. Актор считает нотионал в пределах полосы
// награды по каждой стороне каждый такт и печатает его в сводке
// (depth_bid_usd, depth_ask_usd). В решениях он не участвовал нигде: то, что
// в policy зовётся глубиной, — это дистанция минус половина спреда, к
// ликвидности отношения не имеющая, а посчитанный из неё Quote.Margin
// встречался только в строке лога.
//
// Замер боевого счёта 1 сентября 2026, 23 залива за сутки: 70% из них пришли
// при глубине своей стороны в нижней четверти суточного распределения, а два
// самых крупных (по 10 XAU) — на первом и третьем перцентиле. Ордер ставился
// туда, где перед ним не стояло почти ничего, и сам становился лучшей ценой.
//
// Порог задан долей от собственной недавней нормы, а не суммой в долларах.
// Абсолютное число протухает при первой же смене баланса, инструмента или
// часа суток; отношение к своей же медиане переживает всё это.
package liquidity

import (
	"slices"
	"time"

	"github.com/nd/mm-standx/internal/domain/market"
)

// Config — настройки оценки.
type Config struct {
	// Window — горизонт, по которому считается норма.
	Window time.Duration
	// SampleEvery — минимальный промежуток между замерами.
	//
	// БЕЗ НЕГО ОКНО МЕРЯЕТ НЕ ВРЕМЯ, А СОБЫТИЯ. Observe вызывается из такта
	// актора, а такт идёт по приходу рыночных данных: замер 1 сентября 2026
	// даёт 3.4 обновления стакана в секунду плюс mark и события ордеров.
	// Без прореживания в тридцатиминутном окне копится порядка семи тысяч
	// замеров, и следствий три, каждое портит своё:
	//
	//   - MinSamples в 40 набирается за десять секунд, а не за минуты, то есть
	//     настройка зрелости перестаёт означать написанное;
	//   - медиана считается по семи тысячам значений на каждом такте;
	//   - и главное: частота событий сама зависит от рынка. Busy-периоды
	//     дают больше замеров и перевешивают медиану, то есть норма смещается
	//     ровно тогда, когда она нужнее всего.
	//
	// Ноль возвращает замер на каждом вызове.
	SampleEvery time.Duration
	// MinSamples — сколько замеров нужно, чтобы норме можно было верить.
	// До этого сторона считается пригодной: молчать из-за незрелой оценки
	// значит платить присутствием за отсутствие данных.
	//
	// Считается в замерах, а не в минутах, и вместе с SampleEvery задаёт
	// именно время: 300 при замере раз в секунду — это пять минут.
	MinSamples int
	// ThinFraction — доля медианы окна, ниже которой сторона объявляется
	// тонкой, если просадка продержалась ThinAfter. Ноль отключает проверку
	// целиком.
	ThinFraction float64
	// SevereFraction — доля медианы, ниже которой сторона объявляется тонкой
	// НЕМЕДЛЕННО, без выдержки. Обвал, а не просадка. Ноль отключает
	// немедленный путь.
	SevereFraction float64
	// ThinAfter — сколько мягкая просадка обязана продержаться, прежде чем
	// сторона закроется. Ноль — закрывать сразу.
	ThinAfter time.Duration
	// ShortWindow — окно, по которому считается ТЕКУЩАЯ глубина при проверке
	// восстановления. Ноль — сравнивать последний замер.
	//
	// СГЛАЖИВАЕТСЯ ТОЛЬКО ВЫХОД, И ЭТО ПРОВЕРЕНО. Напрашивается сгладить обе
	// проверки — шум глубины к своей же медиане широк (p10 0.47, p90 1.30),
	// и мгновенный замер даёт ложные срабатывания. Но перебор по 1 и 3 сентября
	// 2026 показал, что сглаживание ВХОДА рушит обнаружение: тридцатисекундная
	// медиана не успевает за обвалом, и предотвращённый объём падает с 99%
	// до 51% при любом пороге. Пропускается ровно тот случай, ради которого
	// фильтр и заведён: залив 1 сентября 22:00:35 на 10 XAU шёл при мгновенных
	// 0.62, когда медиана ещё стояла на месте.
	//
	// На выходе спешить некуда, и там сглаживание работает по назначению:
	// снимает дребезг, не трогая чувствительность.
	ShortWindow time.Duration
	// RecoverFraction — доля медианы, выше которой глубина считается
	// восстановившейся. Обязана быть выше ThinFraction: иначе порог один,
	// и глубина, дрожащая вокруг него, дёргает сторону туда-обратно.
	// Ноль — восстановление по ThinFraction.
	RecoverFraction float64
	// RecoverAfter — сколько глубина обязана простоять выше RecoverFraction,
	// прежде чем сторона откроется. Ноль — открывать сразу.
	RecoverAfter time.Duration
}

// Verdict — что известно о стороне прямо сейчас.
type Verdict struct {
	// Ready сообщает, набралось ли замеров для суждения.
	Ready bool
	// Thin — глубина упала ниже доли от нормы.
	Thin bool
	// DepthUSD — текущий нотионал в полосе награды.
	DepthUSD float64
	// MedianUSD — норма по окну.
	MedianUSD float64
	// ThresholdUSD — граница, ниже которой сторона тонка.
	ThresholdUSD float64
}

type sample struct {
	at    time.Time
	depth float64
}

// Estimator хранит окно наблюдений по каждой стороне.
//
// Владеет им актор и обращается к нему из своей единственной горутины,
// поэтому синхронизации здесь нет и быть не должно.
type Estimator struct {
	cfg  Config
	bids []sample
	asks []sample
	// gate — состояние гистерезиса по сторонам. Вердикт с памятью: сторона,
	// объявленная тонкой, остаётся тонкой, пока глубина не восстановится
	// заметно и надолго, а не на один замер.
	gate [2]gateState
	// scratch переиспользуется под сортировку: медиана считается на каждом
	// такте по обеим сторонам, и аллокация здесь была бы чистым мусором.
	scratch []float64
}

// gateState — память ворот одной стороны.
type gateState struct {
	thin      bool
	thinSince time.Time // с какого момента держится мягкая просадка
	okSince   time.Time // с какого момента глубина выше порога восстановления
}

// New создаёт оценку по конфигурации.
func New(cfg Config) *Estimator { return &Estimator{cfg: cfg} }

func (e *Estimator) gateOf(s market.Side) *gateState {
	if s == market.Buy {
		return &e.gate[0]
	}
	return &e.gate[1]
}

func (e *Estimator) sideOf(s market.Side) *[]sample {
	if s == market.Buy {
		return &e.bids
	}
	return &e.asks
}

// Observe добавляет замер и забывает вышедшие из окна.
//
// Замеры чаще SampleEvery отбрасываются: окно обязано мерить время, а не
// частоту рыночных событий.
func (e *Estimator) Observe(side market.Side, depthUSD float64, at time.Time) {
	if e.cfg.Window <= 0 {
		return
	}
	q := e.sideOf(side)
	if n := len(*q); n > 0 && e.cfg.SampleEvery > 0 &&
		at.Sub((*q)[n-1].at) < e.cfg.SampleEvery {
		return
	}
	*q = append(*q, sample{at: at, depth: depthUSD})
	cutoff := at.Add(-e.cfg.Window)
	drop := 0
	for drop < len(*q) && !(*q)[drop].at.After(cutoff) {
		drop++
	}
	if drop > 0 {
		*q = append((*q)[:0], (*q)[drop:]...)
	}
}

// Verdict судит сторону по последнему замеру — с памятью.
//
// ДВА ПОРОГА И ВЫДЕРЖКА, А НЕ ОДИН ГОЛЫЙ. Первая версия сравнивала глубину
// с одной долей медианы и дёргала сторону при каждом пересечении. Замер
// 2 сентября 2026 за полдня: 515 эпизодов «тонко», медиана длительности
// ОДНА секунда, 90% короче пяти, 379 съёмов стороны. Глубина дрожит вокруг
// порога — сторона снимается и возвращается по кругу, и каждый круг стоит
// четырёх запросов и дыры в присутствии.
//
// Тот же замер показывает, что настоящие обвалы ни с чем не спутать: аск
// в 90 499 USD при норме 7M (1.3%), 528 000 при 6M (9%). Это доля
// SevereFraction, и на неё сторона закрывается немедленно — упреждение
// в сотни миллисекунд, ради которого фильтр и заведён, здесь сохраняется.
// Мягкая просадка до ThinFraction закрывает сторону только продержавшись
// ThinAfter: секундный провал до 65% нормы — это не событие, а шум.
//
// Возврат асимметричен, как и везде в этом контуре: уходим по порогу
// и сразу, возвращаемся по более высокому порогу и с выдержкой.
//
// Пустое окно и незрелая оценка дают Thin=false: проверка существует, чтобы
// убирать актора из опасного стакана, а не чтобы держать его вне рынка, пока
// нечего сказать.
func (e *Estimator) Verdict(side market.Side, now time.Time) Verdict {
	q := *e.sideOf(side)
	g := e.gateOf(side)
	if len(q) == 0 {
		return Verdict{}
	}
	v := Verdict{DepthUSD: q[len(q)-1].depth}
	if e.cfg.ThinFraction <= 0 || len(q) < e.cfg.MinSamples {
		return v
	}
	v.Ready = true
	v.MedianUSD = e.median(q)
	v.ThresholdUSD = v.MedianUSD * e.cfg.ThinFraction
	if v.MedianUSD <= 0 {
		return v
	}
	ratio := v.DepthUSD / v.MedianUSD

	if g.thin {
		recover := e.cfg.RecoverFraction
		if recover <= e.cfg.ThinFraction {
			recover = e.cfg.ThinFraction
		}
		// Выход судится по сглаженной глубине: одиночный высокий замер
		// не повод возвращаться в стакан, который ещё не восстановился.
		if e.smoothed(q, now)/v.MedianUSD >= recover {
			if g.okSince.IsZero() {
				g.okSince = now
			}
			if now.Sub(g.okSince) >= e.cfg.RecoverAfter {
				g.thin, g.okSince, g.thinSince = false, time.Time{}, time.Time{}
			}
		} else {
			g.okSince = time.Time{}
		}
		v.Thin = g.thin
		return v
	}

	switch {
	case e.cfg.SevereFraction > 0 && ratio < e.cfg.SevereFraction:
		g.thin, g.thinSince, g.okSince = true, time.Time{}, time.Time{}
	case ratio < e.cfg.ThinFraction:
		if g.thinSince.IsZero() {
			g.thinSince = now
		}
		if now.Sub(g.thinSince) >= e.cfg.ThinAfter {
			g.thin, g.thinSince = true, time.Time{}
		}
	default:
		g.thinSince = time.Time{}
	}
	v.Thin = g.thin
	return v
}

// smoothed — медиана глубины за ShortWindow, то есть «сколько там сейчас»
// без единичных выбросов. Пустое окно или нулевая настройка дают последний
// замер, то есть прежнее поведение.
func (e *Estimator) smoothed(q []sample, now time.Time) float64 {
	if e.cfg.ShortWindow <= 0 || len(q) == 0 {
		return q[len(q)-1].depth
	}
	cutoff := now.Add(-e.cfg.ShortWindow)
	first := len(q)
	for first > 0 && q[first-1].at.After(cutoff) {
		first--
	}
	if first == len(q) {
		return q[len(q)-1].depth
	}
	return e.median(q[first:])
}

// median — медиана глубины по окну.
//
// Медиана, а не среднее: глубина стакана распределена с тяжёлым правым
// хвостом — одна крупная заявка сдвигает среднее и вместе с ним порог,
// объявляя тонким совершенно обычный стакан.
func (e *Estimator) median(q []sample) float64 {
	e.scratch = e.scratch[:0]
	for _, s := range q {
		e.scratch = append(e.scratch, s.depth)
	}
	slices.Sort(e.scratch)
	return e.scratch[len(e.scratch)/2]
}
